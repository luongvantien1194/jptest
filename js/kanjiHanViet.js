/**
 * Lấy Hán-Việt của một chuỗi kanji.
 * Trả về chuỗi các đọc Hán-Việt viết hoa, cách nhau bằng dấu cách.
 * Chỉ xử lý ký tự CJK, bỏ qua kana và ký tự khác.
 */
window.getHanViet = function(str) {
  if (!str || !window.KANJI_HAN_VIET) return "";
  const parts = [];
  for (const ch of str) {
    const code = ch.codePointAt(0);
    // CJK Unified Ideographs: U+4E00–U+9FFF
    // CJK Extension A: U+3400–U+4DBF
    if ((code >= 0x4E00 && code <= 0x9FFF) ||
        (code >= 0x3400 && code <= 0x4DBF)) {
      const hv = window.KANJI_HAN_VIET[ch];
      if (hv) parts.push(hv);
    }
  }
  return parts.join(" ");
};
